#!/usr/bin/env python3
"""Structured full-Pauli block-encoding counts for Table 3.

For the uniform full n-qubit Pauli sum

    (1 / 4^n) * sum_{P in {I,X,Y,Z}^n} P,

the subgroup basis has 2n address qubits.  A uniform PREPARE is just H on all
address qubits.  SELECT is generated by controlled-X and controlled-Z on each
system qubit, plus a controlled phase that converts XZ into Y when both bits
are active.

The Qrisp baseline still receives the literal full LCU list via
``BlockEncoding.from_lcu``.
"""

from __future__ import annotations

import argparse
import itertools
import json
import sys
import time
import traceback
from pathlib import Path
from typing import Any, Callable


ROOT = Path(__file__).resolve().parents[1]
for candidate in (ROOT / "src", ROOT / "scripts", ROOT / "Baseline_scripts"):
    if str(candidate) not in sys.path:
        sys.path.insert(0, str(candidate))

from qiskit import QuantumCircuit, QuantumRegister  # noqa: E402

from run_mcg_tool_raw_channel_lcu_benchmarks import (  # type: ignore  # noqa: E402
    json_default,
    qiskit_metrics,
    recount_qiskit_circuit,
    timed,
    write_qasm2,
)


RESULT_ROOT = ROOT / "Baseline_results" / "full_pauli_structured_block_encoding_v1"


def full_pauli_labels(num_qubits: int) -> list[str]:
    return ["".join(chars) for chars in itertools.product("IXYZ", repeat=num_qubits)]


def full_pauli_closed_form_circuit(num_qubits: int) -> QuantumCircuit:
    x_ctrl = QuantumRegister(num_qubits, "x")
    z_ctrl = QuantumRegister(num_qubits, "z")
    sys_reg = QuantumRegister(num_qubits, "sys")
    qc = QuantumCircuit(x_ctrl, z_ctrl, sys_reg, name=f"full_pauli_n{num_qubits}_closed_form")

    for qubit in list(x_ctrl) + list(z_ctrl):
        qc.h(qubit)

    for index in range(num_qubits):
        qc.cx(x_ctrl[index], sys_reg[index])
        qc.cz(z_ctrl[index], sys_reg[index])
        qc.cp(-3.141592653589793 / 2, x_ctrl[index], z_ctrl[index])

    for qubit in list(x_ctrl) + list(z_ctrl):
        qc.h(qubit)
    return qc


def qrisp_pauli_unitary(label: str) -> Callable[..., None]:
    def unitary(qv: Any) -> None:
        from qrisp import x, y, z

        for idx, char in enumerate(label):
            if char == "I":
                continue
            if char == "X":
                x(qv[idx])
            elif char == "Y":
                y(qv[idx])
            elif char == "Z":
                z(qv[idx])
            else:
                raise ValueError(f"Unsupported Pauli character {char!r}")

    unitary.__name__ = f"pauli_{label}"
    return unitary


def recount_bases(qc: QuantumCircuit, out_dir: Path, prefix: str) -> dict[str, Any]:
    rows: dict[str, Any] = {}
    for basis in ("nam", "ibm"):
        status, result, elapsed, error = timed(
            lambda basis=basis: recount_qiskit_circuit(
                qc,
                basis_name=basis,
                out_path=out_dir / f"{prefix}_{basis}_opt0.qasm",
                optimization_level=0,
            )
        )
        rows[basis] = {
            "status": status,
            "elapsed_seconds": elapsed,
            "result": result,
            "error": error,
        }
    return rows


def summarize_basis(entry: dict[str, Any] | None) -> dict[str, Any] | None:
    if not entry or entry.get("status") != "ok" or entry.get("result") is None:
        return None
    stats = entry["result"]["stats"]
    return {
        "gate_count": int(stats["metric_total"]),
        "width": int(stats["num_qubits"]),
        "non_clifford": int(stats["clifford"]["non_clifford"]),
        "ops": stats["ops"],
        "qasm": entry["result"]["qasm"],
        "elapsed_seconds": float(entry["elapsed_seconds"]),
        "transpile_time_s": float(entry["result"]["transpile_time_s"]),
    }


def count_closed_form(num_qubits: int, out_dir: Path) -> dict[str, Any]:
    started = time.perf_counter()
    qc = full_pauli_closed_form_circuit(num_qubits)
    prefix = f"full_pauli_n{num_qubits}_closed_form"
    result: dict[str, Any] = {
        "method": "ours_full_pauli_subgroup_closed_form",
        "status": "ok",
        "num_qubits": int(num_qubits),
        "term_count": int(4**num_qubits),
        "address_width": int(2 * num_qubits),
        "qiskit_metrics": qiskit_metrics(qc),
        "qasm": write_qasm2(qc, out_dir / f"{prefix}_logical.qasm"),
    }
    result["basis_recounts"] = recount_bases(qc, out_dir, prefix)
    result["basis_summary"] = {
        basis: summarize_basis(entry)
        for basis, entry in result["basis_recounts"].items()
    }
    result["elapsed_seconds"] = float(time.perf_counter() - started)
    return result


def count_qrisp_full_lcu(num_qubits: int, out_dir: Path, workspace: int) -> dict[str, Any]:
    import qrisp
    from qrisp import QuantumVariable
    from qrisp.block_encodings import BlockEncoding

    labels = full_pauli_labels(num_qubits)
    coeff = 1.0 / float(len(labels))
    coeffs = [coeff] * len(labels)
    unitaries = [qrisp_pauli_unitary(label) for label in labels]
    result: dict[str, Any] = {
        "method": "qrisp_full_pauli_from_lcu",
        "workspace": int(workspace),
        "num_qubits": int(num_qubits),
        "term_count": int(len(labels)),
        "index_width": int(2 * num_qubits),
        "qrisp_version": getattr(qrisp, "__version__", None),
        "qrisp_file": getattr(qrisp, "__file__", None),
    }

    started_total = time.perf_counter()
    status, be, elapsed, error = timed(lambda: BlockEncoding.from_lcu(coeffs, unitaries, is_hermitian=False))
    result["from_lcu_build"] = {"status": status, "elapsed_seconds": elapsed, "error": error}
    if status != "ok":
        result["status"] = "from_lcu_error"
        result["elapsed_seconds"] = float(time.perf_counter() - started_total)
        return result

    result["block_encoding"] = {
        "alpha": repr(be.alpha),
        "num_ancs": int(be.num_ancs),
        "num_ops": int(be.num_ops),
        "is_hermitian": bool(be.is_hermitian),
    }

    qv = QuantumVariable(num_qubits, name="sys")
    status, _unused, elapsed, error = timed(lambda: be.apply(qv))
    result["apply"] = {"status": status, "elapsed_seconds": elapsed, "error": error}
    if status != "ok":
        result["status"] = "apply_error"
        result["elapsed_seconds"] = float(time.perf_counter() - started_total)
        return result

    status, compiled, elapsed, error = timed(lambda: qv.qs.compile(workspace=workspace))
    result["compile"] = {"status": status, "elapsed_seconds": elapsed, "error": error}
    if status != "ok":
        result["status"] = "compile_error"
        result["elapsed_seconds"] = float(time.perf_counter() - started_total)
        return result

    result["compiled_qrisp_metrics"] = {
        "num_qubits": int(compiled.num_qubits()),
        "depth": int(compiled.depth()),
        "ops": {str(k): int(v) for k, v in compiled.count_ops().items()},
    }
    status, qiskit_qc, elapsed, error = timed(compiled.to_qiskit)
    result["to_qiskit"] = {"status": status, "elapsed_seconds": elapsed, "error": error}
    if status != "ok":
        result["status"] = "to_qiskit_error"
        result["elapsed_seconds"] = float(time.perf_counter() - started_total)
        return result

    prefix = f"full_pauli_n{num_qubits}_qrisp_from_lcu"
    result["qiskit_metrics"] = qiskit_metrics(qiskit_qc)
    result["qasm"] = write_qasm2(qiskit_qc, out_dir / f"{prefix}_qiskit.qasm")
    result["basis_recounts"] = recount_bases(qiskit_qc, out_dir, prefix)
    result["basis_summary"] = {
        basis: summarize_basis(entry)
        for basis, entry in result["basis_recounts"].items()
    }
    result["status"] = "ok"
    result["elapsed_seconds"] = float(time.perf_counter() - started_total)
    return result


def row_for(case: dict[str, Any], basis: str, method_key: str) -> dict[str, Any]:
    result = case.get(method_key, {})
    summary = result.get("basis_summary", {}).get(basis)
    if result.get("status") != "ok" or summary is None:
        return {
            "case": case["case"],
            "basis": basis,
            "method": method_key,
            "status": result.get("status", "missing"),
            "gate_count": None,
            "non_clifford": None,
            "width": None,
            "elapsed_seconds": result.get("elapsed_seconds"),
            "error": result.get("error"),
        }
    return {
        "case": case["case"],
        "basis": basis,
        "method": method_key,
        "status": "ok",
        "gate_count": int(summary["gate_count"]),
        "non_clifford": int(summary["non_clifford"]),
        "width": int(summary["width"]),
        "elapsed_seconds": float(result.get("elapsed_seconds", 0.0)),
        "error": None,
    }


def comparison_rows(cases: list[dict[str, Any]]) -> list[dict[str, Any]]:
    rows = []
    for case in cases:
        for basis in ("nam", "ibm"):
            ours = row_for(case, basis, "ours_full_pauli_subgroup_closed_form")
            qrisp = row_for(case, basis, "qrisp_full_pauli_from_lcu")
            if ours["gate_count"] and qrisp["gate_count"]:
                qrisp["qrisp_over_ours"] = float(qrisp["gate_count"] / ours["gate_count"])
            else:
                qrisp["qrisp_over_ours"] = None
            ours["qrisp_over_ours"] = None
            rows.extend([ours, qrisp])
    return rows


def run_case(num_qubits: int, out_dir: Path, workspace: int, *, skip_qrisp: bool) -> dict[str, Any]:
    case_dir = out_dir / f"full_pauli_n{num_qubits}"
    case_dir.mkdir(parents=True, exist_ok=True)
    case: dict[str, Any] = {
        "case": f"full_pauli_n{num_qubits}",
        "metadata": {
            "family": "full_pauli_group_uniform",
            "scope": "single Pauli-sum over all n-qubit Paulis including identity",
            "coefficient": f"1/{4**num_qubits}",
            "closed_form_note": "Uniform PREPARE is H^{2n}; SELECT uses X/Z address bits and a controlled phase for Y.",
        },
        "metrics": {
            "system_qubits": int(num_qubits),
            "term_count": int(4**num_qubits),
            "unique_terms": int(4**num_qubits),
            "has_identity": True,
            "l1_norm": 1.0,
            "natural_width": int(2 * num_qubits),
        },
    }
    try:
        case["ours_full_pauli_subgroup_closed_form"] = count_closed_form(num_qubits, case_dir)
    except Exception:
        case["ours_full_pauli_subgroup_closed_form"] = {
            "status": "runner_exception",
            "error": traceback.format_exc(),
        }

    if skip_qrisp:
        case["qrisp_full_pauli_from_lcu"] = {
            "status": "skipped",
            "reason": "explicit --skip-qrisp",
        }
    else:
        try:
            case["qrisp_full_pauli_from_lcu"] = count_qrisp_full_lcu(num_qubits, case_dir, workspace)
        except Exception:
            case["qrisp_full_pauli_from_lcu"] = {
                "status": "runner_exception",
                "error": traceback.format_exc(),
            }
    return case


def write_report(summary: dict[str, Any], path: Path) -> None:
    lines = [
        "# Structured Full-Pauli Block-Encoding",
        "",
        "| case | basis | method | status | gates | non-Clifford | width | time (s) | qrisp/ours |",
        "| --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for row in summary["comparison_rows"]:
        lines.append(
            f"| {row['case']} | {row['basis']} | {row['method']} | {row['status']} | "
            f"{'-' if row['gate_count'] is None else row['gate_count']} | "
            f"{'-' if row['non_clifford'] is None else row['non_clifford']} | "
            f"{'-' if row['width'] is None else row['width']} | "
            f"{'-' if row['elapsed_seconds'] is None else f'{row['elapsed_seconds']:.3f}'} | "
            f"{'' if row.get('qrisp_over_ours') is None else f'{row['qrisp_over_ours']:.6g}'} |"
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n", type=int, nargs="+", default=[6, 8])
    parser.add_argument("--out-dir", type=Path, default=RESULT_ROOT)
    parser.add_argument("--workspace", type=int, default=0)
    parser.add_argument("--skip-qrisp", action="store_true")
    args = parser.parse_args()

    out_dir = args.out_dir.resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    summary: dict[str, Any] = {
        "experiment": "full_pauli_structured_block_encoding",
        "result_dir": str(out_dir),
        "arguments": vars(args),
        "cases": [],
        "comparison_rows": [],
    }
    for n in args.n:
        case = run_case(n, out_dir, args.workspace, skip_qrisp=args.skip_qrisp)
        summary["cases"].append(case)
        summary["comparison_rows"] = comparison_rows(summary["cases"])
        (out_dir / "summary.partial.json").write_text(
            json.dumps(summary, indent=2, default=json_default),
            encoding="utf-8",
        )
        write_report(summary, out_dir / "report.partial.md")

    summary["comparison_rows"] = comparison_rows(summary["cases"])
    (out_dir / "summary.json").write_text(
        json.dumps(summary, indent=2, default=json_default),
        encoding="utf-8",
    )
    write_report(summary, out_dir / "report.md")
    print(json.dumps(summary["comparison_rows"], indent=2, default=json_default))


if __name__ == "__main__":
    main()
